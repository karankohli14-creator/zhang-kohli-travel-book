function renderRestoredPhotos(pageNumber) {
  const layer = document.getElementById("photoRestoration");
  layer.replaceChildren();
  for (const photo of restoredPhotos) {
    if (photo.page !== pageNumber) continue;
    const img = document.createElement("img");
    img.src = photo.src;
    img.alt = photo.alt;
    img.className = "restored-photo";
    const [x, y, width, height] = photo.frame;
    Object.assign(img.style, { left: `${x / 720 * 100}%`, top: `${y / 960 * 100}%`, width: `${width / 720 * 100}%`, height: `${height / 960 * 100}%` });
    layer.append(img);
  }
}
